/**
 * 按年份取当年"在场"的实体。
 * 时间轴以年为粒度，因此判断用的是"该年是否与存在区间有交集"，不是"1 月 1 日是否在场"——
 * 否则 1940.03 成立的汪伪政权会在 1940 年整年被漏掉。
 */
// ── 年内取点规则（重要）──────────────────────────────────────────────
// 时间轴是**整数年步进**，但数据是 `年.月`。若按「本年任一时段有效」筛选，
// 1949 年会同时命中 1945.08–1949.12 与 1949.10–1949.12 两段，疆域叠成怪色；
// 1949 年 4 月才渡江、10 月才建国这类年内剧变也无从体现。
// 因此统一取**该年年末快照**（12 月）：地图表达的是「这一年结束时中国的样子」，
// 年内过程交给事件图钉与阶段卡叙述。需要看中途态势时用上一年。
const SNAP_END = 0.99;

/** 某年的快照时间点（年末）。 */
export function snapPoint(year) {
  return Math.floor(Number(year)) + SNAP_END;
}

export function factionsAtYear(year) {
  const p = snapPoint(year);
  return FACTIONS.filter((f) => f.start <= p && f.end > p).map((f) => {
    const segs = (f.segs || []).filter((s) => s.start <= p && s.end > p);
    return { ...f, activeSegs: segs };
  });
}

/** 取某一实体在某年的控制区（年末快照）。 */
export function segsAtYear(faction, year) {
  const p = snapPoint(year);
  return (faction.segs || []).filter((s) => s.start <= p && s.end > p);
}
