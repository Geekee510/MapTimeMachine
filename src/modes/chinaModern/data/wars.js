function party(id, arr, color) {
  const [name, troops] = arr;
  return { id, name, short: shortName(name), color, troops: troops || '' };
}

function mkForce(p, p0, p1, from, to) {
  // 路线：出发地 → 中点（略偏，避免直线）→ 交战点
  const mid = [(from[0] + to[0]) / 2 + (to[1] - from[1]) * 0.06, (from[1] + to[1]) / 2 - (to[0] - from[0]) * 0.06];
  return { party: p.id, route: [from, mid, to], p0, p1 };
}

function expand(r) {
  const [start, end] = r.y;
  const loc = r.loc;
  const a = party('a', r.a, PAL[r.ca] || '#b2543a');
  const b = party('b', r.b, PAL[r.cb] || '#2f6f86');
  const fromA = r.a[2] || loc;
  const fromB = r.b[2] || loc;
  return {
    id: r.id,
    meta: { title: r.t, era: r.era, group: r.g, start, end, place: r.p, desc: r.d, result: r.r },
    parties: [a, b],
    forces: [mkForce(a, 0, 0.82, fromA, loc), mkForce(b, 0.08, 0.88, fromB, loc)],
    battles: [{ name: r.t, at: end, loc, winner: r.w === 'b' ? 'b' : 'a', desc: r.r }],
  };
}

export const MODERN_WARS = ROWS.map(expand);

export function modernWarById(id) {
  return MODERN_WARS.find((w) => w.id === id) || null;
}

export function modernWarsAtYear(year) {
  // 结束年月取 floor：1944.08 是一场 1944 年结束的仗，ceil 会把它算到 1945
  // （ceil(1944.08) = 1945），于是"衡阳保卫战"在 1945 年也会被列出来。
  return MODERN_WARS.filter((w) => year >= Math.floor(w.meta.start) && year <= Math.floor(w.meta.end));
}

const GROUP_ORDER = ['晚清', '军阀', '红军', '抗战', '解放'];

export function modernWarGroups() {
  const byGroup = new Map(GROUP_ORDER.map((g) => [g, []]));
  for (const w of MODERN_WARS.slice().sort((a, b) => a.meta.start - b.meta.start)) {
    const g = w.meta.group || '其他';
    if (!byGroup.has(g)) byGroup.set(g, []);
    byGroup.get(g).push(w);
  }
  return [...byGroup.entries()].filter(([, ws]) => ws.length).map(([group, wars]) => ({ era: group, wars }));
}
