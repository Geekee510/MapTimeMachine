//   view    [西, 南, 东, 北] 经纬度取景框，按 Mercator 投影铺满画布
//   routes  行军线：{ name, color, pts:[[lng,lat]…], delay, dur }
//           delay/dur 都是本段内的相对进度（0–1），不是秒——速度由播放器统一控制
//   marks   地点标注：{ at, text, sub }（城市、战场、会议……）
//   star    本段落点：{ at, text, sub }，播放结束时弹出（会师或里程碑，同一套视觉）
//   lead    这一段为什么重要（不是复述战况）
//   bullets 3–4 条硬事实，供右侧叙事卡逐条读
//
// 路线坐标取自现有 LONG_MARCH（长征四路），建军与根据地两段补写。
// 均为示意位置，不承担边界精度。
// =============================================================================

