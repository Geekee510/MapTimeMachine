/** 该年份的铁路通车状态：progress 0–1 表示修到几成（0 不开工、1 全线通车）。
 *  实测口径：`years` = [开工年, 全线通车年]。这两端之间按线性插值"生长"，
 *  比"只按开工年一次性整条画出"更接近史实——陇海路 1905 开工、1952 才通到兰州，
 *  若 1905 年就整条画出，等于把四十多年后的路提前半个世纪画上地图。 */
export function railwaysAtYear(year) {
  return RAILWAYS.map((r) => {
    const [a, b] = r.years;
    const progress = year < a ? 0 : year >= b ? 1 : (year - a) / Math.max(1, b - a);
    return { ...r, progress };
  }).filter((r) => r.progress > 0);
}
