// 当前年份的城市名：取最后一个起始年 ≤ year 的别名；早于首个别名时用最早的名称。
export function cityNameAt(city, year) {
  const list = city?.n;
  if (!list || !list.length) return city?.name || '';
  if (!Number.isFinite(year)) return list[list.length - 1][1];
  let name = list[0][1];
  for (const [y, nm] of list) {
    if (y <= year) name = nm;
    else break;
  }
  return name;
}

// 该年已存在的城市（早于建城年不显示）
export function citiesAtYear(year) {
  if (!Number.isFinite(year)) return CITIES.slice();
  return CITIES.filter((c) => year >= (c.from ?? -9999));
}

// 曾用名串（卡片用）：只列与自身不同的名字
export function cityAliasText(city) {
  const list = city?.n || [];
  const fy = (y) => (y < 0 ? `前${-y}` : `${y}`);
  return list.map(([y, nm]) => `${nm}（${fy(y)}）`).join(' · ');
}

export function cityById(id) {
  return CITIES.find((c) => c.id === id) || null;
}
