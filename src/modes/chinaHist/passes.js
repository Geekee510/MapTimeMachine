// 年份筛选：关隘是"人造工事"，有自己的兴废。
//   from 之前 → 尚未设置，不显示（战国地图上不该出现明长城关隘）
//   until 之后 → 已废弃，不显示（唐代以后的玉门关、阳关旧址不再是关）
// 边界含端点：from 当年即出现，until 当年仍在。
export function passesAtYear(year) {
  if (!Number.isFinite(year)) return PASSES.slice();
  return PASSES.filter((p) => year >= p.from && (p.until == null || year <= p.until));
}

export function passById(id) {
  return PASSES.find((p) => p.id === id) || null;
}
