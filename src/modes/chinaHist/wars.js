// 展开成完整 schema（供渲染/卡片/导入编辑器共用同一结构）
function expand(r) {
  // 年份区间统一成 [早, 晚]。公元前写 [ -1046, -1046.05 ] 时后者在前，
  // 这里自动纠正，数据端不必纠结负数的"更晚"是更小还是更大。
  const [start, end] = r.y[0] <= r.y[1] ? r.y : [r.y[1], r.y[0]];
  const span = Math.max(0.12, end - start);
  const loc = r.loc;
  const party = (key, raw, color) => {
    const [name, troops, from] = raw;
    return { id: key, name, short: shortName(name) || name, color, troops: troops || '', from };
  };
  const route = (from, to) => {
    // 两段式路线：中点做一点侧向弯曲（≈ 直线长度的 6‰），避免疆域上出现死板直线
    const dx = to[0] - from[0];
    const dy = to[1] - from[1];
    const L = Math.hypot(dx, dy) || 1;
    const nx = -dy / L;
    const ny = dx / L;
    const bow = L * 0.06;
    return [
      from,
      [from[0] + dx * 0.5 + nx * bow, from[1] + dy * 0.5 + ny * bow],
      to,
    ];
  };
  const mkForce = (p, t0, t1) => ({ party: p.id, t0, t1, route: route(p.from, loc) });
  const a = party('a', r.a, A_COLOR);
  const b = party('b', r.b, B_COLOR);
  return {
    id: r.id,
    meta: {
      title: r.t, era: r.era, group: r.g,
      start, end,
      place: r.p,
      desc: r.d,
      result: r.r,
    },
    parties: [a, b],
    forces: [
      mkForce(a, start, start + span * 0.8),
      mkForce(b, start + span * 0.1, start + span * 0.86),
    ],
    battles: [
      { name: r.t, at: end, loc, winner: r.w === 'b' ? 'b' : 'a', desc: r.r },
    ],
  };
}

export const WARS = ROWS.map(expand);

export function warById(id) {
  return WARS.find((w) => w.id === id) || null;
}

// 该年份是否有战争在进行（按整数年落入区间判断）
export function warsAtYear(year) {
  return WARS.filter((w) => year >= Math.floor(w.meta.start) && year <= Math.ceil(w.meta.end));
}

// 动画驱动用的"在演战争"：指定 focusId 时只演这一场（列表页跳转后单独回放）。
export function activeWars(year, focusId) {
  if (focusId) {
    const one = WARS.filter((w) => w.id === focusId);
    if (one.length) return one;
  }
  return [];
}

// 列表页分组（用数据里的 g 字段，顺序固定；不靠年份猜时代，避免"长平算进秦汉"）
const GROUP_ORDER = ['先秦', '秦末楚汉', '西汉', '东汉', '三国', '两晋南北朝', '隋', '唐', '五代十国', '北宋', '南宋', '元', '明'];

export function warListGroups() {
  const byGroup = new Map(GROUP_ORDER.map((g) => [g, []]));
  for (const w of WARS.slice().sort((a, b) => a.meta.start - b.meta.start)) {
    const g = w.meta.group || '其他';
    if (!byGroup.has(g)) byGroup.set(g, []);
    byGroup.get(g).push(w);
  }
  return [...byGroup.entries()]
    .filter(([, wars]) => wars.length)
    .map(([group, wars]) => ({ era: group, wars }));
}

// 战区包围盒 → 跳转时的地图中心与缩放
export function warView(w) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const add = ([x, y]) => {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  };
  for (const f of w.forces || []) (f.route || []).forEach(add);
  for (const b of w.battles || []) add(b.loc);
  if (!Number.isFinite(minX)) return { center: [104, 34], zoom: 4.6 };
  const cx = (minX + maxX) / 2;
  const cy = (minY + maxY) / 2;
  const span = Math.max(maxX - minX, maxY - minY, 0.8);
  // 屏幕宽约 1000px：可见经度 ≈ 1000 * 360 / (256 * 2^z) → 反解 zoom
  const zoom = Math.max(4.2, Math.min(8, Math.log2((1000 * 360) / (256 * span * 2.4))));
  return { center: [cx, cy], zoom };
}
