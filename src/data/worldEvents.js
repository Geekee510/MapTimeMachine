// 分类标签显示顺序（用于浮层内排序）
const CAT_ORDER = { 政: 0, 战: 1, 经: 2, 文: 3, 科: 4 };

// 取某一年份的世界大事；未收录返回空数组（调用方据此显示提示）。
export function getWorldEvents(year) {
  const list = WORLD_EVENTS[Number(year)];
  if (!list || !list.length) return [];
  return list
    .map((e) => ({ t: e.t, d: e.d || '', cat: e.cat || '政' }))
    .sort((a, b) => (CAT_ORDER[a.cat] ?? 9) - (CAT_ORDER[b.cat] ?? 9));
}
