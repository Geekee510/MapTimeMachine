/**
 * 合并两卷。
 * 只按年份做一次**稳定**排序：同年内主干卷在前、增补卷在后，各自保持书写顺序。
 * 不在这里去重——同一年出现两条不同的事是常态，跨卷重号留给 createEventCollector
 * 按标题判重（那边有子串 + 字符重合度两道规则）。
 */
export const CHINA_EVENTS = [...OWN_EVENTS, ...EXTRA_EVENTS].sort((a, b) => a.y - b.y);

/** 按年份建索引。年份取整，负数直接作键。 */
const BY_YEAR = new Map();
for (const e of CHINA_EVENTS) {
  const k = Math.trunc(e.y);
  if (!BY_YEAR.has(k)) BY_YEAR.set(k, []);
  BY_YEAR.get(k).push(e);
}

/** 某一年发生的大事（严格同年，不含跨年）。 */
export function chinaEventsOfYear(year) {
  return BY_YEAR.get(Math.trunc(Number(year))) || [];
}

/**
 * 距某年最近的**前一件 / 后一件**大事（允许跨年）。
 *
 * 用途只有一个：这一年没有收录条目时，别让面板只留一句"暂无"。
 * 编年再密也做不到年年有事（三千七百年、近四百条，平均十年一条），
 * 与其硬凑，不如老实交代"上回发生什么、下回发生什么"，年份的位置感就出来了。
 */
export function nearestChinaEvents(year) {
  const y = Math.trunc(Number(year));
  let prev = null;
  let next = null;
  for (const e of CHINA_EVENTS) {
    const ey = Math.trunc(e.y);
    if (ey < y) prev = e;
    else if (ey > y) { next = e; break; }  // 已按 y 升序，第一个更大的就是下一条
  }
  return { prev, next };
}

/** 已收录事件的年份数（用于自检/统计）。 */
export const CHINA_EVENT_YEARS = BY_YEAR.size;

// ── 合并去重 ────────────────────────────────────────────────────────────────
// 编年库与朝代卡片的 events 讲同一件事时会写出不同标题：
//   "安史之乱爆发" vs "安史之乱"（子串）
//   "秦灭齐，天下一统" vs "秦灭六国统一天下"（同义改写）
// 前一种按子串判重，后一种按字符集重合度（Jaccard）判重。阈值 0.6 是试出来的：
// "孔子诞生/孔子卒" 0.4、"商鞅变法/商鞅车裂" 0.33 都安全通过。
const normTitle = (t) => String(t).replace(/[\s·・，,。：:（）()]/g, '');

function charOverlap(a, b) {
  const A = new Set(a);
  const B = new Set(b);
  let inter = 0;
  for (const ch of A) if (B.has(ch)) inter++;
  return inter / (A.size + B.size - inter || 1);
}

/** 建一个"同一年内按标题去重"的收集器。 */
export function createEventCollector() {
  const items = [];
  const keys = [];
  return {
    items,
    push(t, d, c) {
      if (!t) return;
      const k = normTitle(t);
      if (!k) return;
      for (const had of keys) {
        const short = k.length <= had.length ? k : had;
        if (short.length >= 3 && (k.includes(had) || had.includes(k))) return;
        if (k.length >= 4 && had.length >= 4 && charOverlap(k, had) >= 0.6) return;
      }
      keys.push(k);
      items.push({ t, d, cat: c });
    },
  };
}
