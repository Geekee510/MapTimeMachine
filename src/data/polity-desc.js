// 由经纬度粗略判断所属地理区域（用于兜底文案"位于XX"）。
// 只需粗粒度，按优先级依次匹配。
export function regionOf(lon, lat) {
  if (lon == null || lat == null) return '';
  if (lat < -50) return '南极地区';
  if (lon >= 110 && lon <= 180 && lat <= -5 && lat >= -50) return '大洋洲';
  if (lon >= 130 && lon <= 190 && lat > -50 && lat <= -5) return '大洋洲';
  if (lon >= 100 && lon <= 150 && lat >= 18 && lat <= 55) return '东亚';
  if (lon >= 92 && lon <= 142 && lat >= -11 && lat < 25) return '东南亚';
  if (lon >= 60 && lon <= 95 && lat >= 5 && lat < 40) return '南亚';
  if (lon >= 45 && lon < 95 && lat >= 35 && lat < 58) return '中亚';
  if (lon >= 25 && lon < 65 && lat >= 10 && lat < 42) return '西亚';
  if (lon >= -20 && lon < 52 && lat < 16 && lat >= -36) return '撒哈拉以南非洲';
  if (lon >= -18 && lon <= 38 && lat >= 16 && lat <= 37) return '北非／撒哈拉';
  if (lon >= -12 && lon <= 45 && lat > 35 && lat <= 72) return '欧洲';
  if (lon >= -170 && lon <= -50 && lat >= 25 && lat <= 72) return '北美';
  if (lon >= -120 && lon <= -58 && lat >= 5 && lat < 25) return '中美洲／加勒比';
  if (lon >= -85 && lon <= -32 && lat >= -56 && lat < 13) return '南美';
  if (lat >= 58) return '北极／亚北极地区';
  return '';
}

// 按年份取简介（支持 [[起,止,文案]] 形式）
export function polityDesc(en, year) {
  const v = POLITY_DESC[en];
  if (!v) return null;
  if (typeof v === 'string') return v;
  if (year == null || !Number.isFinite(year)) return v[v.length - 1][2];
  for (const [a, b, t] of v) if (year >= a && year <= b) return t;
  return v[v.length - 1][2];
}

