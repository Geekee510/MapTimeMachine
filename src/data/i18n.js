// 单词 → 音译汉字串
function tlWord(w) {
  const s = w.replace(/[^a-z']/g, '');
  if (!s || s.length > 22) return '';
  let out = '';
  let i = 0;
  let guard = 0;
  while (i < s.length && guard++ < 40) {
    let onset = '';
    for (const k of TL_ONSET_KEYS) {
      if (s.startsWith(k, i)) { onset = k; break; }
    }
    const vi0 = i + onset.length;
    let vIdx = -1;
    let vi = vi0;
    for (const k of TL_VOWEL_KEYS) {
      if (s.startsWith(k, vi0)) { vIdx = TL_VOWEL[k]; vi = vi0 + k.length; break; }
    }
    if (vIdx < 0) {
      // 该辅音后没有元音 → 丢弃（如 "Bundjalung" 里 ndj 的 n、词尾的 ng）
      i += Math.max(1, onset.length);
      continue;
    }
    out += onset ? TL_ONSET[onset][vIdx] : TL_STANDALONE_VOWEL[vIdx];
    i = vi;
    if (out.length >= 6) break;
  }
  return out;
}

function transliterate(en) {
  const s = (en || '')
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '') // 去掉变音符号（é、ĩ…）
    .toLowerCase()
    .replace(/\(.*?\)/g, ' ') // 去掉括注："Nuxwsa'7aq (Nooksack)" → "Nuxwsa'7aq"
    .replace(/[^a-z\s'\-/]/g, ' ')
    .trim();
  if (!s) return null;
  // 多词名（"Dja Dja Wurrung"、"Abenaki / Abénaquis"）逐词音译，用间隔号连接
  const words = s.split(/[\s\-/]+/).filter(Boolean).slice(0, 3);
  const parts = words.map(tlWord).filter(Boolean).slice(0, 2);
  if (!parts.length) return null;
  return parts.join('·');
}

// 主名翻译：优先历史政权表 → 现代国名表 → 音译 → null
function headZh(raw) {
  const s = (raw || '').trim();
  if (!s) return null;
  if (HB_ZH[s]) return HB_ZH[s].replace(/（.*?）/g, ''); // 去掉括注，避免"宋（宋朝）帝国"
  return (
    COUNTRY_ZH[norm(s)] ||
    COUNTRY_ZH[norm(s.replace(/\s*\(.*\)\s*$/, ''))] ||
    COUNTRY_ZH[norm(s.split(/[,(]/)[0])] ||
    transliterate(s) ||
    null
  );
}

// 宗主国括号："Algeria (France)" → "法属阿尔及利亚"
function colonialZh(en) {
  const br = (en || '').trim().match(/^(.+?)\s*\(([^)]+)\)\s*$/);
  if (!br) return null;
  const prefix = COLONIAL_PREFIX[br[2].trim()];
  const head = headZh(br[1]);
  return prefix && head ? prefix + head : null;
}

// 规则化翻译历史政权名（无法翻译时返回 null，交由调用方回退英文）
function translatePolity(en) {
  const n = (en || '').trim();
  if (!n) return null;

  // 2) Viceroyalty of X → X总督区
  const vi = n.match(/^Viceroyalty of (?:the )?(.+)$/i);
  if (vi) return (headZh(vi[1]) || vi[1].trim()) + '总督区';

  // 3) <主名> <政体词>：Song Empire → 宋帝国
  for (const w of SUFFIX_ORDER) {
    const re = new RegExp(`^(.+?)\\s+${w}$`, 'i');
    const m = n.match(re);
    if (m && m[1].trim()) return (headZh(m[1]) || m[1].trim()) + POLITY_SUFFIX_ZH[w];
  }

  // 4) <政体词> of (the) <主名>：Kingdom of the Two Sicilies → 两西西里王国
  for (const w of SUFFIX_ORDER) {
    const re = new RegExp(`^${w} of (?:the )?(.+)$`, 'i');
    const m = n.match(re);
    if (m && m[1].trim()) return (headZh(m[1]) || m[1].trim()) + POLITY_SUFFIX_ZH[w];
  }

  // 5) 连字符组合：Poland-Lithuania → 波兰-立陶宛
  if (/^[A-Za-zÀ-ÿ'’-]+-[A-Za-zÀ-ÿ'’-]+$/.test(n)) {
    const parts = n.split('-').map(headZh);
    if (parts.every(Boolean)) return parts.join('-');
  }
  return null;
}

// 取中文译名，未收录则回退原名。
// 依次：历史政权表 → 现代国名表 → 规则化组合 → 去括号 → 括号前主名
export function zhCountry(en) {
  if (!en) return en;
  const hb = HB_ZH[en];
  if (hb) return hb;
  // 宗主国括号优先于"去括号回退"，否则 "Algeria (France)" 会丢掉"法属"
  const colonial = colonialZh(en);
  if (colonial) return colonial;
  const direct =
    COUNTRY_ZH[norm(en)] ||
    COUNTRY_ZH[norm(en.replace(/\s*\(.*\)\s*$/, ''))] ||
    COUNTRY_ZH[norm(en.split(/[,(]/)[0])];
  if (direct) return direct;
  const tl = translatePolity(en) || transliterate(en);
  if (tl) return tl;
  // 最后兜底：原名是"非拉丁文字（民族自称）"但带英文括注，如 "𐓏𐒰…(Osage)"，取括注里的名字
  const br = en.trim().match(/\(([^)]+)\)\s*$/);
  if (br) {
    const inner = zhCountry(br[1]);
    if (inner && inner !== br[1]) return inner;
  }
  return en;
}

